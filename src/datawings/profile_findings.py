"""Profile every raw table and draft findings from it.

1. Builds a ydata-profiling report per table -> reports/profile/<table>.html (for reading).
2. Pulls the alerts out of the report objects (not by scraping the HTML), adds a few checks
   ydata doesn't do (duplicate keys, stray spaces, case/spacing variants), and writes them as
   DRAFT rows into docs/findings.md, between two markers. Rerunning replaces only that block,
   so your own rows above it are never touched.

The "how it's handled" column is left as TODO on purpose: fix / flag / drop / assume is your call.
Once you've decided on a row, move it up into the main table.

Run:  uv run python -m datawings.profile_findings
"""

import os
import re
from datetime import date

# ydata-profiling sends usage analytics to packages.ydata.ai by default. Not with challenge data.
os.environ.setdefault("YDATA_PROFILING_NO_ANALYTICS", "True")

import pandas as pd
from ydata_profiling import ProfileReport

from datawings.config import ROOT, TABLES
from datawings.load import load_table

PROFILE_DIR = ROOT / "reports" / "profile"
FINDINGS = ROOT / "docs" / "findings.md"
START, END = "<!-- profile:start -->", "<!-- profile:end -->"

PKS = {
    "crew": "crew_id",
    "qualification": "qual_id",
    "duty": "duty_id",
    "duty_leg": "duty_leg_id",
    "flight": "flight_key",
    "disruption_event": "event_id",
    "ftl_rule": "rule_id",
}
IS_KEY = re.compile(r"(_id|_key)$")


def describe_alert(alert, n: int) -> str | None:
    """One readable sentence per ydata alert. None = not worth a finding."""
    kind, v = alert.alert_type_name, alert.values or {}
    col = alert.column_name
    if kind == "Unique" and col and IS_KEY.search(col):
        return None  # a unique ID is expected, not a finding
    if kind == "Missing":
        return f"{v.get('n_missing', 0):,} missing ({v.get('p_missing', 0):.1%})"
    if kind == "Constant":
        return "only one value; carries no information"
    if kind == "Zeros":
        return (
            f"{v.get('n_zeros', 0):,} zeros ({v.get('p_zeros', 0):.1%}); real zero or placeholder?"
        )
    if kind == "Imbalance":
        return "heavily imbalanced categories"
    if kind == "High cardinality":
        return f"high cardinality ({v.get('n_distinct', '?'):,} distinct) for a text column"
    if kind == "Unique":
        return "every value unique; is this actually an ID?"
    if kind == "Unsupported":
        return "type couldn't be inferred (mixed types?)"
    return kind.lower()


def extra_checks(df: pd.DataFrame, table: str) -> list[tuple[str, str]]:
    """Checks ydata doesn't do. Returns (column, finding) pairs."""
    out = []
    n_dup = int(df.duplicated().sum())
    if n_dup:
        out.append(("(row)", f"{n_dup:,} exact duplicate rows"))
    pk = PKS.get(table)
    if pk in df:
        dup_pk = int(df[pk].duplicated(keep=False).sum())
        if dup_pk:
            out.append((pk, f"{dup_pk:,} rows share a key value: not unique"))
    for col in df.select_dtypes(include=["object", "string"]).columns:
        s = df[col].dropna().astype(str)
        if s.empty:
            continue
        padded = int((s != s.str.strip()).sum())
        if padded:
            out.append((col, f"{padded:,} values with leading/trailing spaces"))
        raw_n, norm_n = s.nunique(), s.str.strip().str.upper().nunique()
        if not IS_KEY.search(col) and norm_n < raw_n <= 200:
            out.append((col, f"{raw_n} spellings collapse to {norm_n} after trim + upper"))
    return out


def build_rows() -> list[list[str]]:
    PROFILE_DIR.mkdir(parents=True, exist_ok=True)
    today, rows = date.today().isoformat(), []
    for table in TABLES:
        df = load_table(table)
        report = ProfileReport(df, title=f"{table} (typed raw)", minimal=True, progress_bar=False)
        report.to_file(PROFILE_DIR / f"{table}.html", silent=True)
        for alert in report.get_description().alerts:
            text = describe_alert(alert, len(df))
            if text:
                rows.append([table, alert.column_name or "(table)", text])
        rows += [[table, col, text] for col, text in extra_checks(df, table)]
        print(f"{table:<18} profiled, {sum(r[0] == table for r in rows)} draft findings")
    return [[f"P{i}", today, f"{t}.{c}", f, "TODO", ""] for i, (t, c, f) in enumerate(rows, 1)]


def write_findings(rows: list[list[str]]) -> None:
    lines = [
        START,
        "",
        "## Draft findings from profiling (auto-generated, triage me)",
        "",
        "Regenerated by `uv run python -m datawings.profile_findings`. Decide fix / flag / drop /",
        "assume for each, then move the row up into the main table and give it a real number.",
        "",
        "| # | date | table.column | finding | how it's handled | impact |",
        "|---|---|---|---|---|---|",
        *("| " + " | ".join(r) + " |" for r in rows),
        "",
        END,
    ]
    block = "\n".join(lines)
    text = FINDINGS.read_text(encoding="utf-8") if FINDINGS.exists() else "# Findings\n"
    if START in text and END in text:
        text = text[: text.index(START)] + block + text[text.index(END) + len(END) :]
    else:
        text = text.rstrip() + "\n\n" + block + "\n"
    FINDINGS.write_text(text, encoding="utf-8")
    print(f"Wrote {len(rows)} draft rows to {FINDINGS.relative_to(ROOT)}")


def main() -> None:
    write_findings(build_rows())


if __name__ == "__main__":
    main()
